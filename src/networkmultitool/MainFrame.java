private void batDauWorker(
        javax.swing.SwingWorker<String, Void> worker) {

    currentWorker = worker;

    btnPing.setEnabled(false);
    btnTrace.setEnabled(false);
    btnScan.setEnabled(false);

    btnStop.setEnabled(true);
    btnClear.setEnabled(false);

    worker.execute();
}

private void ketThucWorker(
        javax.swing.SwingWorker<String, Void> worker) {

    if (currentWorker != worker) {
        return;
    }

    if (worker.isCancelled()) {
        txtResults.setText("Da dung tac vu.");
    }

    currentWorker = null;

    btnPing.setEnabled(true);
    btnTrace.setEnabled(true);
    btnScan.setEnabled(true);

    btnStop.setEnabled(false);
    btnClear.setEnabled(true);
}


